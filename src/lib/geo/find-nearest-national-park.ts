/**
 * Converts degrees into 16-point cardinal compass directions
 */
export function get16PointCardinal(degrees: number): string {
  const normalized = ((degrees % 360) + 360) % 360;
  const directions = [
    'N', 'NNE', 'NE', 'ENE',
    'E', 'ESE', 'SE', 'SSE',
    'S', 'SSW', 'SW', 'WSW',
    'W', 'WNW', 'NW', 'NNW',
  ];
  const index = Math.round(normalized / 22.5) % 16;
  return directions[index];
}

/**
 * Calculates estimated driving distance and time from direct straight-line distance
 * Road tortuosity factor: ~1.28x direct distance
 * Average highway driving speed: ~58 mph (93 km/h)
 */
export function estimateRoadTravel(distanceMiles: number): { estimatedDriveMiles: number; estimatedDriveHours: number } {
  // Road factor ranges between 1.25 to 1.35 depending on geography
  const factor = 1.28;
  const estimatedDriveMiles = Math.round(distanceMiles * factor);
  const estimatedDriveHours = parseFloat((estimatedDriveMiles / 58).toFixed(1));
  return { estimatedDriveMiles, estimatedDriveHours };
}

/**
 * Finds the nearest national parks to any given origin coordinate
 */
export function findNearestNationalParks(
  originLat: number,
  originLng: number,
  options: ParkFilterOptions = {}
): NearestParkResult[] {
  const { maxResults = 10, maxRadiusMiles, state, searchQuery } = options;

  let candidates = [...US_NATIONAL_PARKS];

  // Optional state filter
  if (state && state !== 'ALL') {
    const s = state.toUpperCase();
    candidates = candidates.filter((p) => p.state.toUpperCase().includes(s));
  }

  // Optional search query (name or highlight)
  if (searchQuery && searchQuery.trim()) {
    const q = searchQuery.toLowerCase().trim();
    candidates = candidates.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.fullName.toLowerCase().includes(q) ||
        p.stateFull.toLowerCase().includes(q) ||
        p.state.toLowerCase().includes(q) ||
        p.highlights.some((h) => h.toLowerCase().includes(q))
    );
  }

  const results: NearestParkResult[] = candidates.map((park) => {
    const geodesic = calculateGeodesic(
      { lat: originLat, lng: originLng },
      { lat: park.lat, lng: park.lng }
    );

    const distanceMeters = geodesic.distanceMeters;
    const distanceMiles = parseFloat((distanceMeters / 1609.344).toFixed(1));
    const distanceKm = parseFloat((distanceMeters / 1000).toFixed(1));
    const bearingDegrees = Math.round(geodesic.initialBearingDeg);
    const cardinalBearing = get16PointCardinal(bearingDegrees);
    const { estimatedDriveMiles, estimatedDriveHours } = estimateRoadTravel(distanceMiles);

    return {
      park,
      distanceMeters,
      distanceMiles,
      distanceKm,
      bearingDegrees,
      cardinalBearing,
      estimatedDriveMiles,
      estimatedDriveHours,
    };
  });

  // Sort by straight-line geodesic distance ascending
  results.sort((a, b) => a.distanceMeters - b.distanceMeters);

  // Filter by max radius if provided
  let filtered = results;
  if (maxRadiusMiles && maxRadiusMiles > 0) {
    filtered = filtered.filter((r) => r.distanceMiles <= maxRadiusMiles);
  }

  // Cap at maxResults if provided
  if (maxResults && maxResults > 0) {
    filtered = filtered.slice(0, maxResults);
  }

  return filtered;
}

/**
 * Generates an RFC-4180 CSV export of nearest national parks results
 */
export function exportNearestParksToCSV(
  results: NearestParkResult[],
  originLabel: string = 'Custom Origin'
): string {
  const headers = [
    'Rank',
    'National Park',
    'State',
    'Direct Distance (Miles)',
    'Direct Distance (KM)',
    'Bearing (Degrees)',
    'Cardinal Direction',
    'Estimated Drive (Miles)',
    'Estimated Drive (Hours)',
    'Established Year',
    'Area (Acres)',
    'Annual Visitors',
    'UNESCO Status',
    'NPS URL',
  ];

  const escapeCSV = (val: string | number | undefined | null) => {
    if (val === undefined || val === null) return '""';
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return `"${str}"`;
  };

  const rows = results.map((r, index) => [
    index + 1,
    escapeCSV(r.park.fullName),
    escapeCSV(r.park.state),
    r.distanceMiles,
    r.distanceKm,
    r.bearingDegrees,
    escapeCSV(r.cardinalBearing),
    r.estimatedDriveMiles,
    r.estimatedDriveHours,
    r.park.establishedYear,
    r.park.areaAcres,
    r.park.annualVisitors,
    escapeCSV(r.park.unescoStatus || 'None'),
    escapeCSV(r.park.npsUrl),
  ]);

  const comments = `# GeoMapSuite Find Nearest National Park Export\n# Origin: ${originLabel}\n# Generated: ${new Date().toISOString()}\n`;
  const csvContent = comments + [headers.join(','), ...rows.map((row) => row.join(','))].join('\n');
  return csvContent;
}

