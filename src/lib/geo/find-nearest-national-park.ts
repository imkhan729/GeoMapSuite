import { calculateGeodesic } from './geodesic';

export interface NationalPark {
  id: string;
  name: string;
  fullName: string;
  state: string; // 2-letter state code or multiple e.g. "WY, MT, ID"
  stateFull: string;
  lat: number;
  lng: number;
  establishedYear: number;
  areaAcres: number;
  areaSqKm: number;
  annualVisitors: number; // approximate benchmark
  description: string;
  unescoStatus?: 'World Heritage Site' | 'Biosphere Reserve';
  npsCode: string;
  npsUrl: string;
  highlights: string[];
}

export interface NearestParkResult {
  park: NationalPark;
  distanceMeters: number;
  distanceMiles: number;
  distanceKm: number;
  bearingDegrees: number;
  cardinalBearing: string;
  estimatedDriveMiles: number;
  estimatedDriveHours: number;
}

export interface ParkFilterOptions {
  maxResults?: number;
  maxRadiusMiles?: number;
  state?: string;
  searchQuery?: string;
}

export interface OriginHubPreset {
  id: string;
  name: string;
  state: string;
  lat: number;
  lng: number;
  description: string;
}

